@router.post("/configs", response_model=ConfigOut, status_code=status.HTTP_201_CREATED)
async def create_config(payload: ConfigCreate, session: SessionDep) -> ServerConfig:
    digest = config_hash(payload.yaml)

    # Content addressing means re-submitting the same YAML is idempotent rather than an
    # error. Sweep authoring will do exactly that, repeatedly.
    existing = await session.scalar(select(ServerConfig).where(ServerConfig.config_hash == digest))
    if existing is not None:
        return existing

    # Lineage is recorded only on creation. A config that already exists has a history
    # that already happened, and letting a later submission rewrite its parent would make
    # the derivation chain depend on who submitted last rather than on what was edited.
    parent_id = None
    if payload.parent_id is not None:
        parent = await session.get(ServerConfig, payload.parent_id)
        if parent is None:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"no config with id {payload.parent_id}",
            )
        parent_id = parent.id

    config = ServerConfig(
        config_hash=digest,
        name=payload.name,
        yaml=normalize_yaml(payload.yaml),
        notes=payload.notes,
        parent_id=parent_id,
    )
    session.add(config)
    await session.commit()
    await session.refresh(config)
    return config


async def _config_by_hash(session: AsyncSession, config_hash_value: str) -> ServerConfig:
    config = await session.scalar(
        select(ServerConfig).where(ServerConfig.config_hash == config_hash_value)
    )
    if config is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="config not found")
    return config


@router.get("/configs/{config_hash_value}/export", response_class=PlainTextResponse)
async def export_config(config_hash_value: str, session: SessionDep) -> Response:
    """The configuration as a file, byte for byte.

    This is the 0.7.0 acceptance criterion in one endpoint: the winning configuration from
    a sweep, exported and run in production unchanged. So nothing is added to it — no
    provenance header, no "generated by" comment, no reordering. A comment would not change
    what vLLM does, but it *would* change the hash, and then the file in production is no
    longer the file that was measured. The point of this endpoint is that those are the
    same bytes.

    The provenance lives at the other end of the link: the hash in the filename is the way
    back to the run that justified it.
    """
    config = await _config_by_hash(session, config_hash_value)
    # Named for what it is and which one it is. A directory of `config.yaml` files tells
    # nobody anything, and the short hash is enough to find the row again.
    filename = f"{_slug(config.name)}-{config.config_hash[:12]}.yaml"
    return PlainTextResponse(
        content=config.yaml,
        media_type="application/yaml",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )


async def _with_justification(session: AsyncSession, config: ServerConfig) -> ConfigOut:
    """A config plus its justification, flattened onto one response.

    Two tables, one payload. The split exists to keep the schema acyclic, not because a
    caller should have to know about it.
    """
    justification = await session.scalar(
        select(ConfigJustification).where(ConfigJustification.server_config_id == config.id)
    )
    out = ConfigOut.model_validate(config)
    if justification is not None:
        out.justified_by_run_id = justification.run_id
        out.justification_note = justification.note
    return out


@router.patch("/configs/{config_hash_value}", response_model=ConfigOut)
async def annotate_config(
    config_hash_value: str, payload: ConfigAnnotate, session: SessionDep
) -> ConfigOut:
    """Change what is *said about* a configuration, never the configuration.

    The YAML is not editable here and there is no endpoint where it is. Editing the text
    produces different bytes, which is a different content hash, which is a different
    configuration — so an edit is a creation, and `parent_id` is what connects the two. A
    config whose text could change would silently invalidate every run that claims it.
    """
    config = await _config_by_hash(session, config_hash_value)

    if payload.name is not None:
        config.name = payload.name
    if payload.notes is not None:
        config.notes = payload.notes

    existing = await session.scalar(
        select(ConfigJustification).where(ConfigJustification.server_config_id == config.id)
    )

    if payload.clear_justification:
        if existing is not None:
            await session.delete(existing)
    elif payload.justified_by_run_id is not None:
        run = await session.get(Run, payload.justified_by_run_id)
        if run is None:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"no run with id {payload.justified_by_run_id}",
            )
        if run.config_hash != config.config_hash:
            # The whole value of the link is that it points at evidence. A run of some
            # other configuration is not evidence for this one, and a link that can be
            # wrong is worse than no link.
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=(
                    "that run did not use this configuration "
                    f"(it ran {run.config_hash[:12]}…), so it cannot justify it"
                ),
            )
        if existing is None:
            session.add(
                ConfigJustification(
                    server_config_id=config.id,
                    run_id=run.id,
                    note=payload.justification_note,
                )
            )
        else:
            existing.run_id = run.id
            if payload.justification_note is not None:
                existing.note = payload.justification_note
    elif payload.justification_note is not None and existing is not None:
        existing.note = payload.justification_note

    await session.commit()
    await session.refresh(config)
    return await _with_justification(session, config)


#: How far back a lineage walk will go before giving up. Deep chains are real — tuning is
#: iterative — but an unbounded walk over a self-referencing column is a query that can
#: hang on data no API path can produce and some future import might.
MAX_LINEAGE_DEPTH = 100


@router.get("/configs/{config_hash_value}/lineage", response_model=LineageOut)
async def config_lineage(config_hash_value: str, session: SessionDep) -> LineageOut:
    """Where this configuration came from, and what came from it.

    One level of children rather than a whole tree: the question a reader has in front of
    a config is "what did I try next", and a full descendant tree of a much-edited
    baseline is a page of noise.
    """
    config = await _config_by_hash(session, config_hash_value)

    ancestors: list[ServerConfig] = []
    seen = {config.id}
    current = config
    truncated = False
    while current.parent_id is not None:
        if len(ancestors) >= MAX_LINEAGE_DEPTH or current.parent_id in seen:
            truncated = True
            break
        parent = await session.get(ServerConfig, current.parent_id)
        if parent is None:
            break
        ancestors.append(parent)
        seen.add(parent.id)
        current = parent

    children = list(
        (
            await session.execute(
                select(ServerConfig)
                .where(ServerConfig.parent_id == config.id)
                .order_by(ServerConfig.created_at.desc())
            )
        ).scalars()
    )

    return LineageOut(
        config_hash=config.config_hash,
        ancestors=[LineageNode.model_validate(a) for a in ancestors],
        children=[LineageNode.model_validate(c) for c in children],
        truncated=truncated,
    )


@router.get("/configs", response_model=list[ConfigOut])
async def list_configs(session: SessionDep) -> list[ConfigOut]:
    """Every configuration, newest first, each with its justification if it has one.

    The justification is joined in here rather than left null, because a list where the
    field is always empty reads as "nothing is justified" rather than "this endpoint does
    not tell you" — and the whole point of recording it is that somebody sees it.
    """
    configs = list(
        (
            await session.execute(select(ServerConfig).order_by(ServerConfig.created_at.desc()))
        ).scalars()
    )

    # Built by hand rather than with dict(rows.all()): a two-column Row resolves to
    # dict's bytes overload, which type-checks and then fails at runtime.
    justifications: dict[uuid.UUID, ConfigJustification] = {}
    for justification in (await session.execute(select(ConfigJustification))).scalars():
        justifications[justification.server_config_id] = justification

    out: list[ConfigOut] = []
    for config in configs:
        item = ConfigOut.model_validate(config)
        if (found := justifications.get(config.id)) is not None:
            item.justified_by_run_id = found.run_id
            item.justification_note = found.note
        out.append(item)
    return out


