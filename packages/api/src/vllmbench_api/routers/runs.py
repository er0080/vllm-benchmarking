@router.post("/runs", response_model=RunOut, status_code=status.HTTP_202_ACCEPTED)
async def create_run(payload: RunCreate, session: SessionDep) -> Run:
    """Queue a run. 202, not 201: the work has been accepted, not done."""
    host = await session.get(GpuHost, payload.gpu_host_id)
    config = await session.get(ServerConfig, payload.server_config_id)
    workload = await session.get(Workload, payload.workload_id)

    missing = [
        name
        for name, value in (
            ("gpu_host_id", host),
            ("server_config_id", config),
            ("workload_id", workload),
        )
        if value is None
    ]
    if missing:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND, detail=f"unknown {', '.join(missing)}"
        )
    assert host is not None and config is not None and workload is not None

    run = Run(
        gpu_host_id=host.id,
        server_config_id=config.id,
        workload_id=workload.id,
        status=RunStatus.QUEUED,
        # Provenance copied at creation, not joined at read time. What is knowable now
        # is recorded now; the rest is filled in by the orchestrator from what actually
        # ran (invariant 6).
        config_hash=config.config_hash,
        workload_hash=workload.workload_hash,
        gpu_count=max(1, host.gpu_count),
        # Invariant 7's chain of custody: the host's declaration, made by the agent
        # itself, decides whether this run is quarantined. Nothing infers it.
        is_synthetic=host.synthetic_source is not None,
        synthetic_source=host.synthetic_source,
        initiated_by=payload.initiated_by,
        initiated_by_client=payload.initiated_by_client,
    )
    session.add(run)
    await session.commit()
    # `summary` is eager-loaded explicitly (it is None for a fresh run) because the
    # relationship is lazy="raise_on_sql". Serializing without this would attempt a lazy
    # load inside the response model and fail — which is precisely what that setting is
    # for: turning a runtime MissingGreenlet into an obvious, immediate error.
    await session.refresh(run, attribute_names=["summary"])
    return run


@router.get("/runs", response_model=list[RunOut])
async def list_runs(session: SessionDep, limit: int = 50) -> list[Run]:
    result = await session.execute(
        select(Run)
        .options(selectinload(Run.summary))
        .order_by(Run.queued_at.desc())
        .limit(min(limit, 200))
    )
    return list(result.scalars())


@router.get("/runs/{run_id}", response_model=RunOut)
async def get_run(run_id: uuid.UUID, session: SessionDep) -> Run:
    run = await session.get(Run, run_id, options=[selectinload(Run.summary)])
    if run is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="run not found")
    return run


def _stride(total: int, budget: int | None) -> int:
    """How many samples to skip so that at most ``budget`` survive.

    1 means "return everything", which is both the unasked-for case and the case where
    the series is already shorter than the budget.
    """
    if budget is None or budget <= 0 or total <= budget:
        return 1
    return -(-total // budget)  # ceiling division


def _thinned(
    model: type[EngineSample] | type[GpuSample],
    run_id: uuid.UUID,
    stride: int,
    partition: InstrumentedAttribute[int] | None,
) -> Select[Any]:
    """Select a series, keeping every ``stride``-th sample **within each partition**.

    The partition is the load-bearing part. `gpu_sample` is keyed per device and stored
    interleaved, so thinning the flat series takes every nth *row*, not every nth
    *reading*: at stride 2 on a two-GPU host that is every sample from device 0 and none
    at all from device 1. The result looks like a healthy single-device series, arrives
    labelled with both devices, and is exactly the imbalance-destroying summary the
    `gpu_sample` keying rule in CLAUDE.md exists to prevent.

    The last sample of each partition is always kept. A run's final reading is the one
    that says what state it ended in, and dropping it because the series length did not
    divide evenly would silently move the end of the chart.
    """
    order = [model.sampled_at, *([partition] if partition is not None else [])]
    if stride == 1:
        return select(model).where(model.run_id == run_id).order_by(*order)

    numbered = (
        select(
            model,
            func.row_number().over(partition_by=partition, order_by=model.sampled_at).label("rn"),
            func.count().over(partition_by=partition).label("total"),
        )
        .where(model.run_id == run_id)
        .subquery()
    )
    entity = aliased(model, numbered)
    keep = or_((numbered.c.rn - 1) % stride == 0, numbered.c.rn == numbered.c.total)
    # Ordered off the subquery's columns rather than the alias's attributes, so this
    # stays one code path for both models instead of needing to know which one it has.
    entity_order = [
        numbered.c.sampled_at,
        *([numbered.c[partition.key]] if partition is not None else []),
    ]
    return select(entity).where(keep).order_by(*entity_order)


@router.get("/runs/{run_id}/telemetry", response_model=RunTelemetryOut)
async def get_run_telemetry(
    run_id: uuid.UUID,
    session: SessionDep,
    max_samples: Annotated[int | None, Query(ge=1)] = None,
) -> RunTelemetryOut:
    """The engine and per-device series for one run.

    A separate endpoint rather than an expansion of the run payload: a long run can carry
    thousands of samples, and the runs list polls every two seconds while anything is in
    flight. Attaching telemetry to that would multiply the cost of the poll by the size
    of the largest run on the page.

    Per device, never aggregated here. One device at 60% while its peer sits at 95% is
    the finding; the mean of the two is not (invariant 8, and the `gpu_sample` keying
    rule in CLAUDE.md).

    `max_samples` thins the response **in the database**, so a caller that wants two
    hundred points out of fourteen thousand does not pay to load fourteen thousand. It
    bounds each series: the engine series, and the GPU series as a whole — the per-device
    budget is the total divided by the device count, so asking for less does not quietly
    cost a device. Unset returns everything, which is what the timeline chart wants.
    """
    if await session.get(Run, run_id) is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="run not found")

    engine_total = (
        await session.scalar(
            select(func.count()).select_from(EngineSample).where(EngineSample.run_id == run_id)
        )
    ) or 0

    # Built by hand rather than with dict(rows.all()): a two-column Row resolves to
    # dict's bytes overload, which type-checks and then fails at runtime.
    per_device: dict[int, int] = {}
    for index, count in (
        await session.execute(
            select(GpuSample.gpu_index, func.count())
            .where(GpuSample.run_id == run_id)
            .group_by(GpuSample.gpu_index)
        )
    ).all():
        per_device[index] = count

    # One stride across every device, taken from the busiest, rather than a stride each.
    # Devices should produce the same number of samples but need not — a failed NVML
    # read on one device is a real thing — and thinning them by different factors would
    # put the two series on different time grids, which is the one thing that makes an
    # imbalance unreadable.
    #
    # The device floor beats the budget: with a budget smaller than the device count,
    # every device still returns a sample. Overshooting a context limit is recoverable;
    # a device that silently is not there is not.
    device_budget = (
        max(1, max_samples // len(per_device)) if max_samples and per_device else max_samples
    )
    engine_stride = _stride(engine_total, max_samples)
    gpu_stride = _stride(max(per_device.values(), default=0), device_budget)

    engine = list(
        (await session.execute(_thinned(EngineSample, run_id, engine_stride, None))).scalars()
    )
    gpu = list(
        (
            await session.execute(_thinned(GpuSample, run_id, gpu_stride, GpuSample.gpu_index))
        ).scalars()
    )

    # An empty series needs its explanation attached, not inferred. "The policy removed
    # this" and "sampling failed" look identical on a chart and mean opposite things.
    pruned = await session.get(RunTelemetryPruned, run_id)

    return RunTelemetryOut(
        run_id=run_id,
        engine=[EngineSampleOut.model_validate(s) for s in engine],
        gpu=[GpuSampleOut.model_validate(s) for s in gpu],
        pruned_at=pruned.pruned_at if pruned else None,
        pruned_horizon_days=pruned.horizon_days if pruned else None,
        # From the counts, not from what came back. These are the devices that sampled,
        # which is a fact about the run rather than about this response.
        gpu_indices=sorted(per_device),
        sample_count=engine_total + sum(per_device.values()),
        stride=max(engine_stride, gpu_stride),
    )


async def resolve_arguments(
    session: AsyncSession, gpu_host_id: uuid.UUID | None
) -> tuple[ServeArguments, bool, int | None]:
    """Pick the argument catalogue to check against, and say how well it fits.

    A host running a version we have no capture for is not an error — the version policy
    in CLAUDE.md makes benchmarking one vLLM against another a first-class use, so this
    falls back to the reference and reports that it did. Silently checking a 0.26 config
    against 0.25's arguments and calling it valid would be the wrong kind of helpful.
    """
    if gpu_host_id is None:
        return reference_serve_arguments(), True, None

    host = await session.get(GpuHost, gpu_host_id)
    if host is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="host not found")

    if host.vllm_version:
        captured = load_serve_arguments(host.vllm_version)
        if captured is not None:
            return captured, True, host.gpu_count
    return reference_serve_arguments(), False, host.gpu_count


@router.post("/configs/validate", response_model=ConfigValidationOut)
async def validate_config_endpoint(
    payload: ConfigValidationRequest, session: SessionDep
) -> ConfigValidationOut:
    """Check a configuration before it costs a model load.

    Reads only. Nothing is stored, nothing is rewritten, and a config that fails here can
    still be created — the engine describes a file, it does not police one. That matters
    because the catalogue is a capture of one vLLM version, and a host running something
    newer may legitimately accept an argument this service has never heard of.
    """
    arguments, exact, gpu_count = await resolve_arguments(session, payload.gpu_host_id)
    result = validate_config(
        payload.yaml,
        arguments,
        gpu_count=gpu_count,
        exact_version_match=exact,
        tensor_parallel_is_swept=payload.tensor_parallel_is_swept,
    )
    return ConfigValidationOut(
        valid=result.valid,
        findings=[
            FindingOut(
                severity=str(f.severity),
                message=f.message,
                key=f.key,
                line=f.line,
                suggestion=f.suggestion,
            )
            for f in result.findings
        ],
        checked_against=result.checked_against,
        exact_version_match=result.exact_version_match,
    )
